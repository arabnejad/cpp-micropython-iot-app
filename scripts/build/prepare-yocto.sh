#!/usr/bin/env bash

# make yocto-prepare calls this script before a Yocto package or image build.
# It prepares directories and configuration but does not run BitBake.

set -euo pipefail

: "${PROJECT_ROOT:?PROJECT_ROOT is required}"
: "${YOCTO_BUILD_DIRECTORY:?YOCTO_BUILD_DIRECTORY is required}"
: "${YOCTO_SOURCE_LINK_DIRECTORY:?YOCTO_SOURCE_LINK_DIRECTORY is required}"
: "${YOCTO_DOWNLOAD_DIRECTORY:?YOCTO_DOWNLOAD_DIRECTORY is required}"
: "${YOCTO_SSTATE_DIRECTORY:?YOCTO_SSTATE_DIRECTORY is required}"
: "${IMAGE_OUTPUT_DIRECTORY:?IMAGE_OUTPUT_DIRECTORY is required}"
: "${ROOT_PARTITION_SIZE_MIB:?ROOT_PARTITION_SIZE_MIB is required}"
: "${DATA_PARTITION_BOOTSTRAP_SIZE_MIB:?DATA_PARTITION_BOOTSTRAP_SIZE_MIB is required}"

yocto_template_directory="$PROJECT_ROOT/meta-iot-app/conf/templates/raspberrypi4-64"
yocto_configuration_directory="$YOCTO_BUILD_DIRECTORY/conf"
yocto_local_configuration="$yocto_configuration_directory/local.conf"
yocto_build_paths_configuration="$yocto_configuration_directory/iot-app-build-paths.conf"
yocto_wifi_configuration="$yocto_configuration_directory/wpa_supplicant.conf"
yocto_ssh_authorized_keys="$yocto_configuration_directory/ssh_authorized_keys"
yocto_storage_layout="$yocto_configuration_directory/iot-app-raspberrypi.wks"
yocto_storage_layout_template="$PROJECT_ROOT/meta-iot-app/wic/iot-app-raspberrypi.wks.in"
yocto_poky_source_link="$YOCTO_SOURCE_LINK_DIRECTORY/poky"
shared_wifi_configuration="$PROJECT_ROOT/wpa_supplicant.conf"
shared_ssh_authorized_keys="$PROJECT_ROOT/ssh_authorized_keys"

ensure_writable_directory() {
  local directory_path="$1"

  if [ ! -d "$directory_path" ]; then
    echo "Creating persistent directory: $directory_path"
    mkdir -p "$directory_path" 2>/dev/null ||
      sudo install -d -m 0755 -o "$(id -u)" -g "$(id -g)" "$directory_path"
  fi

  if [ ! -w "$directory_path" ]; then
    echo "Changing ownership of $directory_path to the current user"
    sudo chown "$(id -u):$(id -g)" "$directory_path"
  fi
}

for source_directory in \
  "$PROJECT_ROOT/poky" \
  "$PROJECT_ROOT/meta-openembedded" \
  "$PROJECT_ROOT/meta-raspberrypi"; do
  if [ ! -d "$source_directory/.git" ] && [ ! -f "$source_directory/.git" ]; then
    echo "Missing Yocto submodule: $source_directory" >&2
    echo "Run: make submodules" >&2
    exit 1
  fi
done

for build_directory in \
  "$YOCTO_BUILD_DIRECTORY" \
  "$YOCTO_SOURCE_LINK_DIRECTORY" \
  "$YOCTO_DOWNLOAD_DIRECTORY" \
  "$YOCTO_SSTATE_DIRECTORY" \
  "$IMAGE_OUTPUT_DIRECTORY"; do
  ensure_writable_directory "$build_directory"
done

if [ -e "$yocto_poky_source_link" ] && [ ! -L "$yocto_poky_source_link" ]; then
  echo "Cannot create the clean Yocto source path because this is not a symbolic link: $yocto_poky_source_link" >&2
  exit 1
fi

ln -sfn "$PROJECT_ROOT/poky" "$yocto_poky_source_link"

if [ ! -f "$yocto_configuration_directory/bblayers.conf" ]; then
  echo "Creating the Raspberry Pi 4 Yocto build directory"
  unset LD_LIBRARY_PATH
  export TEMPLATECONF="$yocto_template_directory"
  # oe-init-build-env creates the build directory and the initial configuration.
  # Poky's script reads optional shell variables that may not be set, so turn
  # off Bash's unset-variable check only while that script runs.
  set +u
  source "$PROJECT_ROOT/poky/oe-init-build-env" "$YOCTO_BUILD_DIRECTORY" >/dev/null
  set -u
  unset TEMPLATECONF
fi

# local.conf is generated from the project template on every preparation run.
# Edit the template when an image setting needs to change.
install -m 0644 "$yocto_template_directory/local.conf.sample" "$yocto_local_configuration"

{
  printf '%s\n' '# Generated by scripts/build/prepare-yocto.sh. Do not edit this file.'
  printf 'COREBASE = "%s"\n' "$yocto_poky_source_link"
  printf 'DL_DIR ?= "%s"\n' "$YOCTO_DOWNLOAD_DIRECTORY"
  printf 'SSTATE_DIR ?= "%s"\n' "$YOCTO_SSTATE_DIRECTORY"
} >"$yocto_build_paths_configuration"

install -m 0600 "$shared_wifi_configuration" "$yocto_wifi_configuration"
echo "Copied the shared Wi-Fi configuration into the Yocto build directory"

if [ -s "$shared_ssh_authorized_keys" ]; then
  install -m 0600 "$shared_ssh_authorized_keys" "$yocto_ssh_authorized_keys"
  echo "The Yocto image will include SSH public keys from $shared_ssh_authorized_keys"
else
  install -m 0600 /dev/null "$yocto_ssh_authorized_keys"
  echo "No non-empty ssh_authorized_keys file was found; password SSH login will remain available"
fi

sed \
  -e "s|@ROOT_PARTITION_SIZE_MIB@|$ROOT_PARTITION_SIZE_MIB|g" \
  -e "s|@DATA_PARTITION_BOOTSTRAP_SIZE_MIB@|$DATA_PARTITION_BOOTSTRAP_SIZE_MIB|g" \
  "$yocto_storage_layout_template" >"$yocto_storage_layout"

echo "Created the Yocto storage layout: $yocto_storage_layout"
echo "Prepared the Yocto configuration: $yocto_local_configuration"
